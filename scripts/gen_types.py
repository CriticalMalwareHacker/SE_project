"""Export JSON Schema from Pydantic models and generate TypeScript types."""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "apps" / "server"))

from guardloop.schemas import (  # noqa: E402
    AgentEvent,
    ConfirmAttempt,
    Finding,
    FixAttempt,
    LogEntry,
    Metrics,
    ReplayResult,
    ScanConfig,
    ScanState,
    Settings,
    TaskNode,
)

OUT = ROOT / "apps" / "web" / "src" / "api" / "types.ts"

HEADER = """// AUTO-GENERATED by scripts/gen_types.py. Do not edit by hand.
// Source: apps/server/guardloop/schemas.py
"""


def _ts_type(prop: dict) -> str:
    if "$ref" in prop:
        return prop["$ref"].split("/")[-1]
    t = prop.get("type")
    if t == "string":
        if "enum" in prop:
            return " | ".join(json.dumps(e) for e in prop["enum"])
        return "string"
    if t == "integer" or t == "number":
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "array":
        return f"{_ts_type(prop.get('items', {'type': 'any'}))}[]"
    if t == "object":
        return "Record<string, unknown>"
    if "anyOf" in prop or "oneOf" in prop:
        parts = prop.get("anyOf", prop.get("oneOf", []))
        return " | ".join(_ts_type(p) for p in parts)
    return "unknown"


def model_to_ts(name: str, schema: dict, defs: dict) -> str:
    props = schema.get("properties", {})
    required = set(schema.get("required", []))
    lines = [f"export interface {name} {{"]
    for pname, pschema in props.items():
        # resolve $defs refs inline naming
        while "$ref" in pschema:
            ref = pschema["$ref"].split("/")[-1]
            pschema = defs.get(ref, {})
        opt = "" if pname in required else "?"
        lines.append(f"  {pname}{opt}: {_ts_type(pschema)};")
    lines.append("}")
    return "\n".join(lines)


def main() -> None:
    models = {
        "ReplayResult": ReplayResult,
        "FixAttempt": FixAttempt,
        "ConfirmAttempt": ConfirmAttempt,
        "Finding": Finding,
        "AgentEvent": AgentEvent,
        "LogEntry": LogEntry,
        "ScanConfig": ScanConfig,
        "ScanState": ScanState,
        "Metrics": Metrics,
        "Settings": Settings,
        "TaskNode": TaskNode,
    }
    # collect defs (enums etc.)
    full: dict = {}
    for m in models.values():
        s = m.model_json_schema()
        full.setdefault("$defs", {}).update(s.get("$defs", {}))
    # enums become union types
    chunks = [HEADER]
    emitted = set()
    for ref, d in full["$defs"].items():
        if d.get("enum"):
            ts = f"export type {ref} = " + " | ".join(json.dumps(e) for e in d["enum"]) + ";"
            chunks.append(ts)
            emitted.add(ref)
    for name, m in models.items():
        s = m.model_json_schema()
        # inline $defs refs: replace {"$ref": "#/$defs/X"} already handled; nested allOf
        props = s.get("properties", {})
        norm: dict = {"properties": {}, "required": s.get("required", [])}
        for k, v in props.items():
            if "allOf" in v and len(v["allOf"]) == 1 and "$ref" in v["allOf"][0]:
                ref = v["allOf"][0]["$ref"].split("/")[-1]
                target = full["$defs"].get(ref, {})
                v = dict(target)
            norm["properties"][k] = v
        chunks.append(model_to_ts(name, norm, full["$defs"]))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    text = "\n\n".join(chunks) + "\n"
    # strip $ref leftovers
    text = re.sub(r"#/\$defs/", "", text)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
